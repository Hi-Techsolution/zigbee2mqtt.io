#!/usr/bin/env python3
"""Extract every GitHub repository link from the zigbee2mqtt.io repo and write
references/github-links.md grouped by the documentation area that cites it.

Usage: python3 -I .claude/skills/zigbee2mqtt-github-links/scripts/extract_links.py [repo_root]
"""
import os, re, sys
from collections import defaultdict

ROOT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '../../../..'))
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'references', 'github-links.md')
SKIP_DIRS = {'node_modules', '.git', '.claude', 'dist', '.vuepress'}
PAT = re.compile(r'https?://github\.com/([A-Za-z0-9_.-]+)/([A-Za-z0-9_.-]+)')
IGNORE_OWNERS = {'user-attachments'}

CATEGORIES = [
    ('Core Zigbee2MQTT projects', lambda r, p: r.split('/')[0].lower() in ('koenkk', 'zigbee2mqtt', 'nerivec') and not r.lower().startswith('koenkk/z-stack')),
    ('Adapter firmware & flashing tools', lambda r, p: '/adapters' in p or 'flashing' in p or 'firmware' in r.lower() or 'flasher' in r.lower() or 'bsl' in r.lower() or 'cclib' in r.lower() or 'cc-tool' in r.lower()),
    ('Device-specific / DIY device firmware', lambda r, p: p.startswith('docs/devices')),
    ('Integrations & third-party tools', lambda r, p: True),
]

def main():
    refs = defaultdict(set)
    canon = {}
    for dp, dns, fns in os.walk(ROOT):
        dns[:] = [d for d in dns if d not in SKIP_DIRS]
        for fn in fns:
            if not fn.endswith(('.md', '.ts', '.js', '.json', '.vue', '.yaml', '.yml')):
                continue
            path = os.path.join(dp, fn)
            rel = os.path.relpath(path, ROOT)
            try:
                text = open(path, encoding='utf-8').read()
            except Exception:
                continue
            for owner, repo in PAT.findall(text):
                repo = re.sub(r'(\.git)?[.)]*$', '', repo)
                if owner in IGNORE_OWNERS or not repo:
                    continue
                key = f'{owner}/{repo}'.lower()
                canon.setdefault(key, f'{owner}/{repo}')
                if owner[0].isupper():
                    canon[key] = f'{owner}/{repo}'
                refs[key].add(rel)
    groups = defaultdict(list)
    for key, files in refs.items():
        name = canon[key]
        files = sorted(files)
        for title, pred in CATEGORIES:
            if any(pred(name, f) for f in files):
                groups[title].append((name, files))
                break
    lines = ['# GitHub repositories referenced by zigbee2mqtt.io', '',
             f'Auto-generated by `scripts/extract_links.py`. {len(refs)} unique repositories.', '']
    for title, _ in CATEGORIES:
        items = sorted(groups.get(title, []), key=lambda x: (-len(x[1]), x[0].lower()))
        if not items:
            continue
        lines += [f'## {title}', '', '| Repository | Cited in (files) | Example source |', '|---|---|---|']
        for name, files in items:
            lines.append(f'| [{name}](https://github.com/{name}) | {len(files)} | `{files[0]}` |')
        lines.append('')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', encoding='utf-8').write('\n'.join(lines))
    print(f'Wrote {len(refs)} repositories to {os.path.normpath(OUT)}')

if __name__ == '__main__':
    main()
